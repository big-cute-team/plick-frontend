/**
 * 아무리 세게 당겨도 콘텐츠가 이만큼(px) 이상은 안 내려온다.
 *
 * 감쇠 곡선(`dampPull`)의 점근선이다. 손가락 이동량을 그대로 쓰면 화면 절반까지
 * 끌려 내려와 목록이 사라지고, 고정 비율로 나누면 끝이 없어 여전히 한없이 내려온다.
 * 당길수록 뻑뻑해지다 이 값에서 멈추는 고무줄 감각을 만들려고 상한을 둔다.
 */
export const PULL_MAX_DISTANCE = 120;

/**
 * 이 거리(px) 이상 내려온 상태에서 손을 떼야 새로고침이 걸린다.
 *
 * 감쇠를 거친 뒤의 거리라 실제 손가락은 75px쯤 움직여야 여기 닿는다. 스크롤을
 * 맨 위에서 살짝 튕겼을 때 의도치 않게 갱신되지 않을 만큼은 멀고, 갱신하려고
 * 마음먹었을 때 손목을 두 번 쓰지 않을 만큼은 가깝다.
 */
export const PULL_TRIGGER_DISTANCE = 64;

/**
 * 갱신이 도는 동안 콘텐츠가 머무는 거리(px).
 *
 * 손을 뗀 자리에 그대로 두면 얼마나 세게 당겼느냐에 따라 스피너 위치가 매번
 * 달라진다. 문턱 바로 아래로 한 번 정리해 항상 같은 자리에서 돌게 한다.
 */
export const PULL_HOLD_DISTANCE = 56;

/**
 * 스피너를 최소한 이 시간(ms)은 보여준다.
 *
 * 캐시가 따끈하거나 응답이 빠르면 스피너가 번쩍하고 만다. 그러면 새로고침이
 * 된 건지 헛당긴 건지 알 수가 없다. 눈에 남을 만큼만 붙잡아 둔다.
 */
export const PULL_MIN_SPIN_MS = 400;

/**
 * 손가락이 이만큼(px) 움직여야 제스처의 방향을 판정한다.
 *
 * 첫 픽셀로 판정하면 홈 맨 위의 가로 캐러셀을 넘기다 손가락이 1px만 아래로
 * 흘러도 새로고침으로 오인한다. 조금 기다렸다가 세로 성분이 가로 성분보다
 * 클 때만 당기기로 받는다.
 */
export const PULL_DIRECTION_SLOP = 8;

/** 손을 뗀 뒤 제자리로 돌아가는 애니메이션 — 모바일 릴 시트와 같은 감속 곡선. */
export const PULL_TRANSITION = "transform 260ms cubic-bezier(0.32, 0.72, 0, 1)";

/**
 * 당겨서 새로고침을 받아줄 뷰포트 조건 — Tailwind `lg`(1024px) 미만.
 *
 * 이 앱은 데스크톱이 기본이고 당기기는 좁은(모바일·태블릿) 화면의 손버릇이라
 * 여기서만 받는다. lg 이상에서 콘텐츠를 transform으로 밀어 내리면 그 순간
 * 사이드바의 `sticky`가 transform 컨테이닝 블록에 걸려 깨지는 실익 없는
 * 부작용도 있다.
 */
export const PULL_VIEWPORT_QUERY = "(max-width: 1023px)";
