/**
 * 화면 좌우 가장자리에서 이 거리(px) 안에 시작한 터치는 받지 않는다.
 *
 * iOS 사파리·웹뷰는 화면 왼쪽 끝에서 시작하는 스와이프를 뒤로가기 제스처로
 * 가로챈다. 같은 터치를 페이저도 받으면 페이지가 뒤로 가면서 리스트도 넘어가는
 * 이중 동작이 된다. 가장자리 시작은 시스템 몫으로 양보한다.
 */
export const SWIPE_EDGE_GUARD = 24;

/**
 * 손가락이 이만큼(px) 움직여야 제스처의 축을 판정한다.
 *
 * 당겨서 새로고침의 `PULL_DIRECTION_SLOP`과 같은 판단이다 — 첫 픽셀로 판정하면
 * 세로 스크롤 중 손가락이 조금만 옆으로 흘러도 팀이 넘어간다. 조금 기다렸다가
 * 가로 성분이 세로 성분보다 클 때만 스와이프로 받는다.
 */
export const SWIPE_DIRECTION_SLOP = 8;

/**
 * 손을 뗐을 때 리스트 폭 대비 이 비율 이상 끌려와 있으면 이웃 팀으로 넘긴다.
 * 절반보다 낮게 둔 이유는 플릭 없이 천천히 끌어도 "넘기려던 참"이라는 의도가
 * 이쯤이면 분명해서다.
 */
export const SWIPE_COMMIT_RATIO = 0.35;

/**
 * 플릭 판정 속도(px/ms). 거리가 문턱에 못 미쳐도 이 속도 이상으로 튕기면 넘긴다.
 * 관성 스크롤 감각과 같다 — 짧고 빠른 스와이프가 가장 흔한 넘김 동작이다.
 */
export const SWIPE_FLICK_VELOCITY = 0.4;

/**
 * 플릭으로 넘기더라도 최소 이 거리(px)는 끌려와 있어야 한다.
 * 속도만 보면 슬롭을 갓 지난 떨림도 플릭으로 오인한다.
 */
export const SWIPE_FLICK_MIN_DISTANCE = 30;

/**
 * 끝 탭(전체·마지막 팀)에서 더 끌 때 콘텐츠가 밀리는 최대 거리(px).
 *
 * 감쇠 곡선(`damp`)의 점근선이다. 당겨서 새로고침(`PULL_MAX_DISTANCE` 120)보다
 * 작게 둔다 — 세로 당김은 스피너가 나올 자리를 만들지만 여기는 "더 없다"는
 * 신호만 주면 되고, 많이 밀리면 오히려 다음 팀이 있는 것처럼 보인다.
 */
export const SWIPE_EDGE_MAX = 64;

/** 손을 뗀 뒤 스냅 애니메이션 — 당겨서 새로고침·릴 시트와 같은 감속 곡선을 쓴다. */
export const SWIPE_SETTLE_TRANSITION =
  "transform 260ms cubic-bezier(0.32, 0.72, 0, 1)";

/**
 * 스냅 정리의 안전 타이머(ms). `transitionend`는 탭 전환·백그라운드 진입으로
 * 빠질 수 있어, 전환 시간(260ms)보다 넉넉한 시점에 시간으로도 정리한다.
 * `ScrollArea`의 settling 정리와 같은 판단이다.
 */
export const SWIPE_SETTLE_TIMEOUT_MS = 400;
